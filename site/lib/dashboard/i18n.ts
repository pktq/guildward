/** Look up a chrome string; `{name}` placeholders are filled from `vars`. Falls back to English, then the key. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number | null | undefined>): string {
  const s = I18N[lang]?.[key] ?? I18N.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : "")) : s;
}
